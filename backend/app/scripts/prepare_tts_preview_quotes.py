def clean_quote(raw: str) -> str:
    """去除序号、出处，返回纯名言文本。"""
    text = raw.strip()
    if not text:
        return ""
    # 去除序号前缀（如 "1. "、"321." 等）
    text = re.sub(r"^\d+\.\s*", "", text)
    # 去除出处后缀（如 "——《书名》（作者）" 或 "——《书名》"）
    text = re.sub(r"。——《[^》]*》（[^）]*）$", "。", text)
    text = re.sub(r"。——《[^》]*》$", "。", text)
    text = re.sub(r"——《[^》]*》（[^）]*）$", "", text)
    text = re.sub(r"——《[^》]*》$", "", text)
    # 去除末尾可能多余的部分（如 "。——《..."）
    text = re.sub(r"。——《.*$", "。", text)
    text = re.sub(r"——《.*$", "", text)
    # 统一标点：将未以句号结尾的补句号
    text = text.strip()
    if text and not text.endswith(("。", "？", "！", ".", "?", "!")):
        text = text + "。"
    # 统一引号
    text = text.replace("“", "\u201c").replace("”", "\u201d")
    return text


def normalize_for_dedup(text: str) -> str:
    """用于去重的归一化：去除首尾空白、标点差异。"""
    t = text.strip()
    # 统一末尾标点（去末尾句号差异）
    t = re.sub(r"[。.？?！!]+$", "", t)
    return t


