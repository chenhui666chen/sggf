"""
质量标准模块

定义各阶段的质量检查标准，包括：
- 通用质量标准
- 阶段专属标准
"""

from typing import Dict, List

# 通用质量标准
COMMON_QUALITY_STANDARDS: str = """【质量标准】
- ✅ 与前面章节的情节连贯一致
- ✅ 人物性格和行为符合已有描写
- ✅ 遵循已建立的世界观规则和设定
- ✅ 延续已有的叙事风格和文笔特点
- ✅ 推进主线情节，避免原地踏步
- ✅ 注重细节的合理性和真实感"""

# 阶段专属质量标准
QUALITY_STANDARDS: Dict[str, str] = {
    # 内容创作质量标准
    "content_creation": """创作要求：
1. 语言生动流畅，描写具体细腻，避免空洞的形容词堆砌
2. 对话自然真实，符合人物性格，不要用对话塞满全部信息
3. 情节推进合理，节奏张弛有度，保持阅读吸引力
4. 场景描写要有画面感和细节感
5. 注意段落分隔，便于阅读
6. 开头要有抓力，结尾要有悬念或情绪余味
7. 综合使用场景描写、对话、心理描写、动作描写等多种手法

""" + COMMON_QUALITY_STANDARDS,

    # 章节规划质量标准
    "chapter_planning": """规划要求：
- 确保与整本书的情节大纲保持一致
- 确保与前面章节的剧情连贯
- 推进故事发展，不能原地踏步
- 爽点和钩子必须具体、可执行""",

    # 大纲扩展质量标准
    "outline_expansion": """扩展要求：
- 章节划分合理，每章有明确的核心事件
- 节奏起伏有序，避免平铺直叙
- 伏笔和悬念分布均匀
- 人物戏份安排得当
- 各卷有清晰的阶段性目标""",

    # 世界观设计质量标准
    "world_building": """设计要求：
- 世界观逻辑自洽，无明显矛盾
- 力量体系清晰明确
- 社会结构合理可信
- 为故事冲突提供足够的舞台""",

    # 人物设计质量标准
    "character_design": """设计要求：
- 人物性格鲜明，有辨识度
- 人物动机合理，行为可理解
- 人物关系网络清晰
- 主要人物有成长空间"""
}


def get_quality_standard(stage: str) -> str:
    """
    获取指定阶段的质量标准
    
    Args:
        stage: 阶段名称
    
    Returns:
        质量标准字符串
    """
    return QUALITY_STANDARDS.get(stage, COMMON_QUALITY_STANDARDS)
