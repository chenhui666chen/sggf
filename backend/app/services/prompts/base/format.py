"""
输出格式模块

定义各阶段的输出格式要求
"""

from typing import Dict

# 输出格式定义
OUTPUT_FORMATS: Dict[str, str] = {
    # 章节内容输出格式
    "chapter_content": """【输出格式要求】⚠️
请直接输出章节内容，格式必须如下：

第X章 章节标题

章节正文内容...

注意：
- 第一行必须是章节标题，格式为"第X章 标题名称"（X为章节数字）
- 章节标题要简洁有力，能概括本章核心内容或悬念
- 不要包含任何额外的说明文字、作者话语等""",

    # 章节规划输出格式
    "chapter_plan": """请按以下结构输出章节规划：

## 1. 本章定位
描述本章在整体故事中的位置和作用

## 2. 核心事件
本章的主要事件和情节推进

## 3. 人物安排
本章涉及的主要人物及其戏份

## 4. 爽点设计
本章的爽点类型、强度、实现方式

## 5. 情绪曲线
本章的情绪走势

## 6. 结尾钩子
本章结尾的悬念或期待点""",

    # 大纲输出格式
    "outline": """请按以下格式输出章节大纲：

第X章：《章节标题》
- 核心事件：...
- 涉及人物：...
- 情节要点：...
- 结尾悬念：...""",

    # 世界观输出格式
    "world_setting": """请按以下结构输出世界观设定：

## 一、世界背景
...

## 二、力量体系
...

## 三、社会结构与势力
...

## 四、重要地点
...

## 五、核心规则与禁忌
...

## 六、历史与传说
...

## 七、资源与货币体系
...""",

    # 人物设定输出格式
    "characters": """请按以下格式输出人物设定：

### 人物名称

**基本信息**：年龄、性别、身份...

**外貌特征**：...

**性格特点**：...

**背景故事**：...

**动机与目标**：...

**人物关系**：与其他角色的关系..."""
}


def get_output_format(stage: str) -> str:
    """
    获取指定阶段的输出格式
    
    Args:
        stage: 阶段名称
    
    Returns:
        输出格式字符串
    """
    return OUTPUT_FORMATS.get(stage, "")
