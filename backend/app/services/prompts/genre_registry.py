def resolve_genre(raw_genre: str) -> str:
    """
    将用户输入的题材名称解析为标准题材键名

    支持精确匹配、模糊匹配和关键词匹配。
    找不到则返回 "通用"。
    """
    if not raw_genre:
        return "通用"

    if raw_genre in GENRE_PROMPT_MODULES:
        return raw_genre

    raw_lower = raw_genre.lower()
    for key in GENRE_PROMPT_MODULES:
        if key.lower() in raw_lower or raw_lower in key.lower():
            return key

    for genre_key, keywords in GENRE_KEYWORD_MAP.items():
        for kw in keywords:
            if kw in raw_genre:
                return genre_key

    return "通用"


def get_genre_module(genre: str) -> Dict[str, str]:
    """
    获取题材完整提示词模块配置

    优先精确匹配，其次模糊匹配，兜底返回 DEFAULT_GENRE_MODULE。
    """
    resolved = resolve_genre(genre)
    if resolved in GENRE_PROMPT_MODULES:
        return GENRE_PROMPT_MODULES[resolved]
    return DEFAULT_GENRE_MODULE


