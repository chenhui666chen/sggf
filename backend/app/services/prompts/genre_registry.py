def get_genre_terminology(genre: str) -> Dict[str, str]:
    """获取题材术语映射"""
    resolved = resolve_genre(genre)
    return GENRE_TERMINOLOGY.get(resolved, {})


def get_all_genres() -> List[str]:
    """获取所有支持的题材列表"""
    return list(SUPPORTED_GENRES)


def get_genre_summary() -> Dict[str, Dict[str, Any]]:
    """获取所有题材配置摘要（用于调试/展示）"""
    summary = {}
    for genre in SUPPORTED_GENRES:
        module = GENRE_PROMPT_MODULES.get(genre, {})
        summary[genre] = {
            "has_world_extension": bool(module.get("world_extra_sections")),
            "has_character_fields": bool(module.get("character_extra_fields")),
            "has_rhythm_guide": bool(module.get("outline_rhythm_guide")),
            "has_chapter_plan_guide": bool(module.get("chapter_plan_guide")),
            "has_chapter_detail_template": bool(module.get("chapter_detail_template")),
            "has_outline_detail_tips": bool(module.get("outline_detail_tips")),
            "has_terminology": genre in GENRE_TERMINOLOGY,
        }
    return summary
